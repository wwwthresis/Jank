"""Pixel-art icon set of Jank! (16x16, two tones).

Every icon is drawn here with a few primitives (or ASCII art) on a 16x16 grid:
0 = empty, 1 = shade (drawn at ~45% opacity), 2 = ink (full opacity). The app tints the
white atlas with the current ink colour, so one set serves every state and accent.

Run from the repository root:
    python3 tools/gen_icons.py            # writes app/src/icon_data.rs
    python3 tools/gen_icons.py --preview  # also writes icons_preview.png (needs Pillow)
No third-party module is needed for the Rust output.
"""
# Pixel-art icon generator for Jank! (16x16, 2 = ink, 1 = shade). Emits Rust data + a preview sheet.
import math
N=16
class C:
    def __init__(s): s.p=[[0]*N for _ in range(N)]
    def px(s,x,y,v=2):
        if 0<=x<N and 0<=y<N: s.p[y][x]=max(s.p[y][x],v) if v>0 else 0
    def clr(s,x,y):
        if 0<=x<N and 0<=y<N: s.p[y][x]=0
    def line(s,x0,y0,x1,y1,v=2):
        dx=abs(x1-x0); dy=-abs(y1-y0); sx=1 if x0<x1 else -1; sy=1 if y0<y1 else -1; e=dx+dy
        while True:
            s.px(x0,y0,v)
            if x0==x1 and y0==y1: break
            e2=2*e
            if e2>=dy: e+=dy; x0+=sx
            if e2<=dx: e+=dx; y0+=sy
    def rect(s,x0,y0,x1,y1,v=2):
        for x in range(x0,x1+1): s.px(x,y0,v); s.px(x,y1,v)
        for y in range(y0,y1+1): s.px(x0,y,v); s.px(x1,y,v)
    def fill(s,x0,y0,x1,y1,v=1):
        for y in range(y0,y1+1):
            for x in range(x0,x1+1): s.px(x,y,v)
    def circle(s,cx,cy,r,v=2,fillv=0):
        # pixel circle on half-pixel centre (cx,cy can be .5)
        for y in range(N):
            for x in range(N):
                d=math.hypot(x+0.5-cx,y+0.5-cy)
                if fillv and d<r-0.5: s.px(x,y,fillv)
                if r-0.5<=d<r+0.5: s.px(x,y,v)
    def disc(s,cx,cy,r,v=2):
        for y in range(N):
            for x in range(N):
                if math.hypot(x+0.5-cx,y+0.5-cy)<r: s.px(x,y,v)
    def poly(s,pts,v=1):
        # scanline fill of polygon at pixel centres
        for y in range(N):
            yc=y+0.5; xs=[]
            for i in range(len(pts)):
                (x0,y0),(x1,y1)=pts[i],pts[(i+1)%len(pts)]
                if (y0<=yc<y1) or (y1<=yc<y0):
                    xs.append(x0+(yc-y0)*(x1-x0)/(y1-y0))
            xs.sort()
            for a,b in zip(xs[::2],xs[1::2]):
                for x in range(N):
                    if a<=x+0.5<=b: s.px(x,y,v)
    def outline(s,pts,v=2):
        for i in range(len(pts)):
            (x0,y0),(x1,y1)=pts[i],pts[(i+1)%len(pts)]
            s.line(x0,y0,x1,y1,v)
    def art(s,rows):
        for y,r in enumerate(rows):
            for x,ch in enumerate(r):
                if ch=='#': s.px(x,y,2)
                elif ch=='+': s.px(x,y,1)
        return s

I={}
def icon(name):
    def deco(f):
        c=C(); f(c); I[name]=c; return f
    return deco

