names = list(I.keys())


def rows(c):
    return [''.join('.+#'[v] for v in r) for r in c.p]


def rust():
    out = ['// Generated by tools/gen_icons.py - edit the drawings there, then regenerate.',
           '// Rows: \'#\' = ink, \'+\' = shade, \'.\' = empty.',
           '',
           '/// Every icon of the pixel set; the order matches [`ICON_ROWS`].',
           '#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]',
           'pub enum Icon {']
    for n in names:
        out.append('    %s,' % n)
    out += ['}', '', 'impl Icon {', '    pub const ALL: [Icon; %d] = [' % len(names)]
    for n in names:
        out.append('        Icon::%s,' % n)
    out += ['    ];', '}', '', 'pub const ICON_ROWS: [(&str, [&str; 16]); %d] = [' % len(names)]
    for n in names:
        out.append('    ("%s", [' % n)
        for r in rows(I[n]):
            out.append('        "%s",' % r)
        out.append('    ]),')
    out.append('];')
    return '\n'.join(out) + '\n'


def preview(path):
    from PIL import Image  # optional, only for the preview sheet
    cols, sc = 12, 6
    w = cols * (N + 2) * sc
    h = ((len(names) + cols - 1) // cols) * (N + 2) * sc
    img = Image.new('RGB', (w, h), (30, 30, 34))
    pal = {0: (40, 40, 45), 1: (120, 120, 130), 2: (230, 230, 235)}
    for i, n in enumerate(names):
        c = I[n]
        ox = (i % cols) * (N + 2) * sc + sc
        oy = (i // cols) * (N + 2) * sc + sc
        for y in range(N):
            for x in range(N):
                for yy in range(sc):
                    for xx in range(sc):
                        img.putpixel((ox + x * sc + xx, oy + y * sc + yy), pal[c.p[y][x]])
    img.save(path)


